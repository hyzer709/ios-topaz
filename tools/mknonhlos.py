#!/usr/bin/env python3
"""Generate the TopazModem firmware tables for a phone from its stock NON-HLOS.bin.

  mknonhlos.py NON-HLOS.bin PREFIX > table.inc

The modem partition is a byte copy of NON-HLOS.bin (a FAT12/16/32 volume), so the
kernel reads firmware files straight from the partition at the offsets listed here,
read-only, without a FAT driver. Emits:
  PREFIX_fw_files[]  image/modem.* (name, offset, size, crc32): the PAS image, one extent each
  PREFIX_fw_ext[]    every extent (offset, length) of every file
  PREFIX_fw_all[]    every file (path, size, first extent, extent count) for the tftp server
Only offsets, sizes, names and checksums are written; no firmware content.
"""
import struct, sys, zlib


def walk(img):
    f = open(img, 'rb')
    bs = f.read(512)
    bps, spc, res, nf, rootn, tot16, _, fsz16 = struct.unpack_from('<HBHBHHBH', bs, 11)
    tot32, = struct.unpack_from('<I', bs, 32)
    fat32 = fsz16 == 0
    fsz = struct.unpack_from('<I', bs, 36)[0] if fat32 else fsz16
    f.seek(res * bps)
    fat = f.read(fsz * bps)
    rootsec = (rootn * 32 + bps - 1) // bps
    data = (res + nf * fsz + rootsec) * bps
    cl = spc * bps
    nclus = ((tot16 or tot32) * bps - data) // cl
    kind = 'FAT32' if fat32 else ('FAT16' if nclus >= 4085 else 'FAT12')

    def nxt(c):
        if kind == 'FAT32':
            return struct.unpack_from('<I', fat, 4 * c)[0] & 0x0fffffff
        if kind == 'FAT16':
            return struct.unpack_from('<H', fat, 2 * c)[0]
        v = struct.unpack_from('<H', fat, c * 3 // 2)[0]
        return v >> 4 if c & 1 else v & 0xfff
    eoc = 0x0ffffff8 if kind == 'FAT32' else (0xfff8 if kind == 'FAT16' else 0xff8)

    def chain(c):
        out = []
        while 2 <= c < eoc and len(out) <= nclus:
            out.append(c)
            c = nxt(c)
        return out

    def rdc(x):
        f.seek(data + (x - 2) * cl)
        return f.read(cl)

    def rd_dir(raw, path):
        lfn = []
        for i in range(0, len(raw), 32):
            e = raw[i:i + 32]
            if e[0] == 0:
                break
            if e[0] == 0xe5:
                lfn = []
                continue
            if e[11] == 0x0f:
                lfn.insert(0, (e[1:11] + e[14:26] + e[28:32]).decode('utf-16le', 'ignore').split('\x00')[0])
                continue
            if lfn:
                name = ''.join(lfn)
            else:
                base, ext = e[0:8].decode('latin1').rstrip(), e[8:11].decode('latin1').rstrip()
                name = (base + ('.' + ext if ext else '')).lower()
            lfn = []
            if e[11] & 0x08 or name in ('.', '..'):
                continue
            c = struct.unpack_from('<H', e, 26)[0]
            if kind == 'FAT32':
                c |= struct.unpack_from('<H', e, 20)[0] << 16
            size, = struct.unpack_from('<I', e, 28)
            p = path + name
            if e[11] & 0x10:
                yield from rd_dir(b''.join(rdc(x) for x in chain(c)), p + '/')
                continue
            ext, rem = [], size
            for x in chain(c):
                o = data + (x - 2) * cl
                if ext and ext[-1][0] + ext[-1][1] == o:
                    ext[-1][1] += cl
                else:
                    ext.append([o, cl])
            out = []
            for o, l in ext:
                t = min(l, rem)
                if t:
                    out.append((o, t))
                rem -= t
            assert rem == 0, f'{p}: cluster chain shorter than the file'
            yield p, size, out

    if fat32:
        root = b''.join(rdc(x) for x in chain(struct.unpack_from('<I', bs, 44)[0]))
    else:
        f.seek((res + nf * fsz) * bps)
        root = f.read(rootn * 32)
    return f, kind, list(rd_dir(root, ''))


def main():
    img, prefix = sys.argv[1], sys.argv[2]
    f, kind, files = walk(img)
    files.sort(key=lambda t: t[0])
    print(f'/* generated by tools/mknonhlos.py from {img.split("/")[-1]} ({kind}, {len(files)} files) */')
    print(f'static const struct fw_file_t {prefix}_fw_files[] = {{')
    for p, s, e in files:
        if p.startswith('image/modem.') and (p[12:13] == 'b' or p.endswith('.mdt')):
            assert len(e) == 1, f'{p} is fragmented'
            f.seek(e[0][0])
            crc = zlib.crc32(f.read(s)) & 0xffffffff
            print(f'\t{{ "{p[6:]}", {e[0][0]:#x}, {s:#x}, {crc:#010x} }},')
    print('};')
    print(f'static const struct fw_ext_t {prefix}_fw_ext[] = {{')
    n = 0
    for p, s, e in files:
        for o, l in e:
            print(f'\t{{ {o:#x}, {l:#x} }},')
            n += 1
    print('};')
    assert n < 0x10000
    print(f'static const struct fw_all_t {prefix}_fw_all[] = {{')
    k = 0
    for p, s, e in files:
        assert '"' not in p and '\\' not in p
        print(f'\t{{ "{p}", {s:#x}, {k}, {len(e)} }},')
        k += len(e)
    print('};')


if __name__ == '__main__':
    main()
